/// Databases compared by file only: the engine merges them, or their top-level key is a
/// wrapper rather than an object.
pub const OBJECT_ANALYSIS_EXCLUDED: &[&str] = &[
    "common/on_action",
    "common/defines",
    "common/genes",
    "common/named_colors",
    "common/coat_of_arms/coat_of_arms",
    "common/landed_titles",
    "common/province_terrain",
];

/// The database a file belongs to: the longest known root containing it, else
/// `common/<first folder>` for files under `common/`.
pub fn database_root(norm_path: &str) -> Option<String> {
    COMMON_DATABASES
        .iter()
        .chain(COMMON_DATABASES_SCANNED)
        .chain(GFX_DATABASES)
        .filter(|root| {
            norm_path
                .strip_prefix(**root)
                .is_some_and(|rest| rest.starts_with('/'))
        })
        .max_by_key(|root| root.len())
        .map(|root| root.to_string())
        .or_else(|| {
            let (dir, _) = norm_path.strip_prefix("common/")?.split_once('/')?;
            Some(format!("common/{dir}"))
        })
}
